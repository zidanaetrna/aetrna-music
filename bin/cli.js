#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const readline = require('readline');
const crypto = require('crypto');
const { execSync } = require('child_process');
const https = require('https');

const CLI_VERSION = 'v2.1.8';
const GITHUB_REPO = 'zidanaetrna/aetrna-music';
const GITHUB_RELEASES_URL = `https://api.github.com/repos/${GITHUB_REPO}/releases/latest`;

function runCmd(cmd, opts = {}) {
    try {
        return execSync(cmd, { encoding: 'utf8', stdio: 'inherit', ...opts });
    } catch (err) {
        return null;
    }
}

function getRemoteLatest() {
    return new Promise((resolve) => {
        const req = https.get(GITHUB_RELEASES_URL, {
            headers: { 'User-Agent': 'aetrna-music-cli-updater' }
        }, (res) => {
            let data = '';
            res.on('data', chunk => data += chunk);
            res.on('end', () => {
                try {
                    if (res.statusCode !== 200) return resolve(null);
                    const json = JSON.parse(data);
                    resolve({ tag: json.tag_name || CLI_VERSION, url: json.html_url || '' });
                } catch (_) {
                    resolve(null);
                }
            });
        });
        req.on('error', () => resolve(null));
        req.setTimeout(5000, () => { req.destroy(); resolve(null); });
    });
}

function renderBanner(title) {
    console.log('\x1b[36m%s\x1b[0m', `
====================================================================
               AETRNA'S MUSIC — ${title || 'CLI WIZARD'} ${CLI_VERSION}
====================================================================
`);
}

async function runSetup() {
    renderBanner('SETUP WIZARD');
    console.log('Welcome! Let\'s set up your self-hosted Discord Music Platform.\n');

    const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
    const askQuestion = (q) => new Promise((res) => rl.question(q, res));

    const envPath = path.join(process.cwd(), '.env');
    if (fs.existsSync(envPath)) {
        const overwrite = await askQuestion('[WARN] A .env file already exists. Overwrite? (y/N): ');
        if (overwrite.trim().toLowerCase() !== 'y') {
            console.log('\n[INFO] Setup cancelled. Keeping existing .env file.\n');
            rl.close();
            return;
        }
    }

    let discordToken = '';
    while (!discordToken) {
        discordToken = (await askQuestion('[TOKEN] Enter your Discord Bot Token (Required): ')).trim();
        if (!discordToken) {
            console.log('\x1b[31m%s\x1b[0m', '[ERROR] Discord Bot Token is required!');
        }
    }

    console.log('\n--- Spotify Integration (Optional) ---');
    const spotifyId = (await askQuestion('[SPOTIFY] Enter Spotify Client ID (Press Enter to skip): ')).trim();
    let spotifySecret = '';
    if (spotifyId) {
        spotifySecret = (await askQuestion('[SPOTIFY] Enter Spotify Client Secret: ')).trim();
    }

    console.log('\n--- Web Dashboard Security ---');
    let dashPassword = (await askQuestion('[SECURITY] Enter Web Dashboard Password (Press Enter for autogenerated token): ')).trim();
    if (!dashPassword) {
        dashPassword = crypto.randomBytes(8).toString('hex');
        console.log('\x1b[33m%s\x1b[0m', `[INFO] Generated random Dashboard Password: ${dashPassword}`);
    }

    console.log('\n--- Port & System Settings ---');
    const port = (await askQuestion('[PORT] Enter HTTP Server Port (Default: 8080): ')).trim() || '8080';

    const envContent = `# ==============================================================================
# Aetrna's Music Configuration (Generated via CLI Setup Wizard)
# ==============================================================================

DISCORD_TOKEN=${discordToken}
SPOTIFY_CLIENT_ID=${spotifyId}
SPOTIFY_CLIENT_SECRET=${spotifySecret}
DASHBOARD_PASSWORD=${dashPassword}

PORT=${port}
PREFIX=/
DEFAULT_VOLUME=1.0
COOKIES_PATH=./cookies.txt
DB_PATH=./data/aetrna.db
CACHE_DIR=./data/cache
MAX_CACHE_SIZE_MB=5120
YTDLP_CLIENTS=ios,web,android,tv
`;

    fs.writeFileSync(envPath, envContent, 'utf-8');
    console.log('\n\x1b[32m%s\x1b[0m', '[OK] .env file successfully created!');

    const cookiesPath = path.join(process.cwd(), 'cookies.txt');
    if (!fs.existsSync(cookiesPath)) {
        console.log('\n\x1b[33m%s\x1b[0m', '[INFO] Notice: cookies.txt not detected.');
        console.log('       YouTube audio extraction works out-of-the-box, but providing a cookies.txt');
        console.log('       prevents potential age-restricted video extraction issues.\n');
    }

    console.log('====================================================================');
    console.log('\x1b[32m%s\x1b[0m', '[SUCCESS] Setup Complete! You are ready to start Aetrna\'s Music.');
    console.log('          Run: docker compose up -d');
    console.log('====================================================================\n');

    rl.close();
}

async function runUpdate() {
    renderBanner('AUTO UPDATER');
    console.log('[INFO] Checking latest published release from GitHub...');
    const remote = await getRemoteLatest();
    if (remote) {
        console.log(`[INFO] Current version: ${CLI_VERSION} | Latest release: ${remote.tag}`);
    }

    const isGitRepo = fs.existsSync(path.join(process.cwd(), '.git'));

    if (isGitRepo) {
        console.log('\n[1/4] Pulling latest updates from Git repository...');
        runCmd('git fetch --tags origin');
        runCmd('git pull origin main');
    } else {
        console.log('\n[1/4] Non-git workspace detected. Updating npm CLI package...');
        runCmd('npm install -g aetrna-music@latest');
    }

    console.log('\n[2/4] Updating yt-dlp binary...');
    const ytDlpUpdated = runCmd('yt-dlp -U') !== null || runCmd('pip install -U yt-dlp') !== null;
    if (!ytDlpUpdated) {
        console.log('[WARN] yt-dlp update command skipped or not in PATH.');
    }

    console.log('\n[3/4] Updating voice-server dependencies...');
    const voiceDir = path.join(process.cwd(), 'voice-server');
    if (fs.existsSync(voiceDir)) {
        runCmd('npm install --prefix voice-server');
    }

    console.log('\n[4/4] Restarting system services...');
    let serviceRestarted = false;

    // Check systemd service
    if (fs.existsSync('/etc/systemd/system/aetrna-music-prod.service') || fs.existsSync('/etc/systemd/system/voice-server.service')) {
        console.log('[INFO] Restarting systemd services (aetrna-music-prod & voice-server)...');
        runCmd('systemctl restart aetrna-music-prod voice-server');
        serviceRestarted = true;
    }

    // Check docker compose
    if (fs.existsSync(path.join(process.cwd(), 'docker-compose.yml')) || fs.existsSync(path.join(process.cwd(), 'compose.yml'))) {
        console.log('[INFO] Restarting Docker Compose containers...');
        runCmd('docker compose pull');
        runCmd('docker compose up -d --build');
        serviceRestarted = true;
    }

    if (!serviceRestarted) {
        console.log('[INFO] No systemd or docker service detected to auto-restart.');
        console.log('       Please restart your bot process manually (e.g. go run ./cmd/bot or npm start).');
    }

    console.log('\n====================================================================');
    console.log('\x1b[32m%s\x1b[0m', '[SUCCESS] Update Complete! Aetrna\'s Music is up to date.');
    console.log('====================================================================\n');
}

function showHelp() {
    renderBanner('CLI HELP');
    console.log(`Usage: npx aetrna-music <command>

Commands:
  setup, init    Run the interactive setup wizard to create .env configuration
  update         Check and pull latest updates, update yt-dlp, and restart services
  version, -v    Show current CLI version
  help, -h       Show CLI usage guide
`);
}

async function main() {
    const args = process.argv.slice(2);
    const subCmd = (args[0] || 'setup').toLowerCase();

    switch (subCmd) {
        case 'setup':
        case 'init':
            await runSetup();
            break;
        case 'update':
        case 'upgrade':
            await runUpdate();
            break;
        case 'version':
        case '-v':
        case '--version':
            console.log(`aetrna-music ${CLI_VERSION}`);
            break;
        case 'help':
        case '-h':
        case '--help':
            showHelp();
            break;
        default:
            console.log(`Unknown command: ${subCmd}\n`);
            showHelp();
            break;
    }
}

main().catch((err) => {
    console.error('[ERROR] CLI Error:', err);
    process.exit(1);
});
