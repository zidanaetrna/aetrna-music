#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const readline = require('readline');
const crypto = require('crypto');

const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout
});

const askQuestion = (query) => new Promise((resolve) => rl.question(query, resolve));

function renderBanner() {
    console.log('\x1b[36m%s\x1b[0m', `
====================================================================
               AETRNA'S MUSIC — SETUP WIZARD v2.1.7
====================================================================
`);
    console.log('Welcome! Let\'s set up your self-hosted Discord Music Platform.\n');
}

async function runWizard() {
    renderBanner();

    const envPath = path.join(process.cwd(), '.env');
    if (fs.existsSync(envPath)) {
        const overwrite = await askQuestion('⚠️  A .env file already exists. Overwrite? (y/N): ');
        if (overwrite.trim().toLowerCase() !== 'y') {
            console.log('\n[INFO] Setup cancelled. Keeping existing .env file.\n');
            rl.close();
            return;
        }
    }

    let discordToken = '';
    while (!discordToken) {
        discordToken = (await askQuestion('🔑 Enter your Discord Bot Token (Required): ')).trim();
        if (!discordToken) {
            console.log('\x1b[31m%s\x1b[0m', '❌ Discord Bot Token is required!');
        }
    }

    console.log('\n--- Spotify Integration (Optional) ---');
    const spotifyId = (await askQuestion('🎵 Enter Spotify Client ID (Press Enter to skip): ')).trim();
    let spotifySecret = '';
    if (spotifyId) {
        spotifySecret = (await askQuestion('🔐 Enter Spotify Client Secret: ')).trim();
    }

    console.log('\n--- Web Dashboard Security ---');
    let dashPassword = (await askQuestion('🛡️  Enter Web Dashboard Password (Press Enter for autogenerated token): ')).trim();
    if (!dashPassword) {
        dashPassword = crypto.randomBytes(8).toString('hex');
        console.log('\x1b[33m%s\x1b[0m', `💡 Generated random Dashboard Password: ${dashPassword}`);
    }

    console.log('\n--- Port & System Settings ---');
    const port = (await askQuestion('🌐 Enter HTTP Server Port (Default: 8080): ')).trim() || '8080';

    const envContent = `# ==============================================================================
# Aetrna's Music Configuration (Generated via CLI Setup Wizard)
# ==============================================================================

DISCORD_TOKEN=${discordToken}
SPOTIFY_CLIENT_ID=${spotifyId}
SPOTIFY_CLIENT_SECRET=${spotifySecret}
DASHBOARD_PASSWORD=${dashPassword}

PORT=${port}
PREFIX=/
DEFAULT_VOLUME=1.0
COOKIES_PATH=./cookies.txt
DB_PATH=./data/aetrna.db
CACHE_DIR=./data/cache
MAX_CACHE_SIZE_MB=5120
YTDLP_CLIENTS=ios,web,android,tv
`;

    fs.writeFileSync(envPath, envContent, 'utf-8');
    console.log('\n\x1b[32m%s\x1b[0m', '✅ .env file successfully created!');

    const cookiesPath = path.join(process.cwd(), 'cookies.txt');
    if (!fs.existsSync(cookiesPath)) {
        console.log('\n\x1b[33m%s\x1b[0m', '💡 Notice: cookies.txt not detected.');
        console.log('   YouTube audio extraction works out-of-the-box, but providing a cookies.txt');
        console.log('   prevents potential age-restricted video extraction issues.\n');
    }

    console.log('====================================================================');
    console.log('\x1b[32m%s\x1b[0m', '🚀 Setup Complete! You are ready to start Aetrna\'s Music.');
    console.log('   Run: docker compose up -d');
    console.log('====================================================================\n');

    rl.close();
}

runWizard().catch((err) => {
    console.error('❌ Setup wizard error:', err);
    rl.close();
    process.exit(1);
});
